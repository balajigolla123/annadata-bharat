  translations.en = baseEn;

  function t(lang, key) {
    return (translations[lang] && translations[lang][key]) || translations['en'][key] || '';
  }

  function translatePage(lang) {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = t(lang, key);
      el.textContent = translation;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.placeholder = t(lang, key);
    });
  }

  function setLanguage(lang) {
    const hasRequested = !!translations[lang];
    const effectiveLang = hasRequested ? lang : 'en';
    localStorage.setItem('selectedLanguage', effectiveLang);
    const select = document.getElementById('languageSelect');
    if (select && select.value !== effectiveLang) {
      select.value = effectiveLang;
    }
    if (!hasRequested && lang && lang !== 'en') {
      console.warn(`Translations for '${lang}' not available — falling back to English.`);
      showTempNotice(`Translations for selected language not yet available — showing English.`);
    }
    translatePage(effectiveLang);
    document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: effectiveLang } }));
  }

  function init() {
    const select = document.getElementById('languageSelect');
    const saved = localStorage.getItem('selectedLanguage') || 'en';
    if (select) {
      select.value = saved;
      select.addEventListener('change', () => {
        setLanguage(select.value || 'en');
      });
    }
    setLanguage(saved);
  }

  function showTempNotice(text) {
    const n = document.createElement('div');
    n.className = 'translation-notice';
    n.textContent = text;
    n.style.position = 'fixed';
    n.style.top = '76px';
    n.style.right = '20px';
    n.style.background = '#fffae6';
    n.style.border = '1px solid #ffd54f';
    n.style.padding = '8px 12px';
    n.style.borderRadius = '8px';
    n.style.zIndex = 9999;
    n.style.boxShadow = '0 6px 18px rgba(0,0,0,0.08)';
    document.body.appendChild(n);
    setTimeout(() => n.remove(), 3800);
  }

  window.i18n = { translatePage, t, set: setLanguage };
  document.addEventListener('DOMContentLoaded', init);
